def area(a, b):
    '''Возвращает площадь прямоугольника со сторонами a и b.

    Параметры:
        a (int/float) - первая сторона прямоугольника.
        b (int/float) - вторая сторона прямоугольника.

    Возвращаемое значение:
        int/float - площадь прямоугольника со сторонами a и b.

    Пример вызова:
        area(5, 10) => 50
    '''
    return a * b

def perimeter(a, b):
    '''Возвращает периметр прямоугольника со сторонами a и b.

    Параметры:
        a (int/float) - первая сторона прямоугольника.
        b (int/float) - вторая сторона прямоугольника.

    Возвращаемое значение:
        int/float - периметр прямоугольника со сторонами a и b.

    Пример вызова:
        perimeter(5, 10) => 30
    '''
    return 2 * (a + b)

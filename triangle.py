def area(a, h):
    '''Возвращает площадь треугольника со стороной a и высотой h, проведенной к этой стороне.

    Параметры:
        a (int, float): сторона треугольника.
        h (int, float): высота, проведенная к стороне a.

    Возваращаемое значение:
        float: площадь треугольника со стороной a и высотой h, проведенной к этой стороне.

    Пример вызова:
        area(5, 10) => 25.0
    '''
    return a * h / 2

def perimeter(a, b, c):
    '''Возвращает периметр треугольника со сторонами a, b и c.

    Параметры:
        a (int, float): первая сторона треугольника.
        b (int, float): вторая сторона треугольника.
        c (int, float): третья сторона треугольника.

    Возвращаемое значение:
        int/float: периметр треугольника со сторонами a, b и с.

    Пример вызова:
        perimeter(5, 10, 15) => 30
    '''
    return a + b + c
